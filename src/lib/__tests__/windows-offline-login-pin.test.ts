import { createRequire } from "node:module";
import { expect,it } from "vitest";
import bcrypt from "bcryptjs";
const { verifySyncedStaffPin,verifySyncedApprovalPin,listSyncedStaff }=createRequire(import.meta.url)("../../../electron/synced-staff-login.cjs");
const login=bcrypt.hashSync("123456",4), approval=bcrypt.hashSync("654321",4);
function pool(active=true,locked=false,terminalHash:string|null=login){
 const queries:string[]=[];
 return {queries,request:()=>({input(){return this;},async query(sql:string){queries.push(sql);
 if(sql.includes("FROM dbo.pin_attempts"))return {recordset:locked?[{locked_until:new Date(Date.now()+60000)}]:[]};
 if(sql.includes("MERGE dbo.pin_attempts"))return {recordset:[{attempts:1}]};
 return {recordset:[{id:"person",username:"admin",full_name:"Admin",email:"admin@example.com",role_slug:"admin",store_id:null,permissions:'{"can_sell":false}',is_active:active,pin_hash:sql.includes("a.offline_login_pin_hash")?terminalHash:approval}]};
 }})};
}
it("verifies the synced offline hash and preserves the user's role and permissions",async()=>{
 const db=pool(); expect(await verifySyncedStaffPin(db,"admin@example.com","123456","branch-a")).toMatchObject({ok:true,staff:{role_slug:"admin",permissions:{can_sell:false}}});
 expect(db.queries[0]).toContain("a.store_id=@branch");
 expect(await verifySyncedStaffPin(db,"admin","654321","branch-a")).toMatchObject({ok:false});
 expect(await verifySyncedApprovalPin(db,"admin","123456","branch-a")).toMatchObject({ok:false});
});
it("rejects wrong PINs, disabled accounts and throttled users",async()=>{
 expect(await verifySyncedStaffPin(pool(),"admin","000000","branch-a")).toMatchObject({ok:false,reason:"invalid"});
 expect(await verifySyncedStaffPin(pool(false),"admin","123456","branch-a")).toMatchObject({ok:false,reason:"inactive"});
 expect(await verifySyncedStaffPin(pool(true,true),"admin","123456","branch-a")).toMatchObject({ok:false,reason:"locked"});
});
it("returns roster metadata without credential hashes",async()=>{
 const result=await listSyncedStaff(pool(),"branch-a"); expect(result.rows[0]).toMatchObject({fullName:"Admin",roleSlug:"admin",pinLength:0});
 expect(result.rows[0]).not.toHaveProperty("pin_hash");
});

it("does not record wrong-PIN attempts when the synchronized terminal verifier is missing",async()=>{
 for(const hash of [null,"","   "]){
  const db=pool(true,false,hash);
  expect(await verifySyncedStaffPin(db,"admin","123456","branch-a")).toMatchObject({ok:false,reason:"missing"});
  expect(db.queries.some(sql=>sql.includes("MERGE dbo.pin_attempts"))).toBe(false);
  expect(db.queries.some(sql=>sql.includes("DELETE FROM dbo.pin_attempts"))).toBe(false);
 }
});

it("preserves an existing lock and independent approval verification when the terminal verifier is missing",async()=>{
 expect(await verifySyncedStaffPin(pool(true,true,null),"admin","123456","branch-a")).toMatchObject({ok:false,reason:"locked"});
 expect(await verifySyncedApprovalPin(pool(true,false,null),"admin","654321","branch-a")).toMatchObject({ok:true});
 const wrong=pool();
 expect(await verifySyncedStaffPin(wrong,"admin","000000","branch-a")).toMatchObject({ok:false,reason:"invalid"});
 expect(wrong.queries.some(sql=>sql.includes("MERGE dbo.pin_attempts"))).toBe(true);
});

it("matches a test-only bcrypt verifier generated by the POS Postgres server",async()=>{
 const hash="$2a$12$jUxaPOQEpp0SgjaN4ig/qu5cTt3Xrh65dJW0WTHExc9Qm5H8a9QA6";
 expect(await bcrypt.compare("test-only-246810",hash)).toBe(true);
 expect(await bcrypt.compare("wrong-test-value",hash)).toBe(false);
});
