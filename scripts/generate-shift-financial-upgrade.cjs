const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const cloudPath = 'supabase/migrations/20261105090000_shift_financial_known_history.sql';
const manifestPath = 'docs/database/shift-financial-upgrade-manifest.json';
const modules = [
  ['shift-financial-math-postgres.sql', false],
  ['shift-financial-cloud-receipts.sql', false],
  ['shift-financial-version-receipts.sql', false],
  ['shift-financial-known-basis.sql', false],
  ['shift-financial-opening-origin.sql', false],
  ['shift-financial-admission.sql', false],
  ['shift-financial-operation-history.sql', false],
  ['shift-financial-web-actions.sql', true],
  ['shift-financial-live-business.sql', true],
  ['shift-financial-admin-aliases.sql', true],
  ['shift-financial-rollout-capability.sql', true],
  ['shift-financial-final-readiness.sql', true],
];
const canonical = text => text.replaceAll('\r\n', '\n').trimEnd() + '\n';
const sha256 = text => crypto.createHash('sha256').update(text, 'utf8').digest('hex').toUpperCase();
const read = relative => canonical(fs.readFileSync(path.join(root, relative), 'utf8'));
function moduleBody(text, wrapped) {
  const beginnings = [...text.matchAll(/^BEGIN;$/gm)], endings = [...text.matchAll(/^COMMIT;$/gm)];
  assert.equal(beginnings.length, wrapped ? 1 : 0, 'Unexpected transaction boundary');
  assert.equal(endings.length, wrapped ? 1 : 0, 'Unexpected transaction boundary');
  if (!wrapped) return text;
  const before = text.slice(0, beginnings[0].index);
  assert(before.split('\n').every(line => !line.trim() || line.trimStart().startsWith('--')), 'Transaction must precede module statements');
  assert.equal(text.slice(endings[0].index + 'COMMIT;'.length).trim(), '', 'Commit must end module');
  return before + text.slice(beginnings[0].index + 'BEGIN;'.length, endings[0].index).trimStart();
}
function renderCloudUpgrade() {
  const sources = modules.map(([name, wrapped]) => {
    const source = 'scripts/preparation/' + name, text = read(source);
    return { source, sha256: sha256(text), body: moduleBody(text, wrapped) };
  });
  const header = `-- FIN62 RELEASE CANDIDATE: NOT APPROVED FOR LIVE APPLICATION.
-- Generated by scripts/generate-shift-financial-upgrade.cjs. UTF-8/LF, no BOM.
-- Schema/routine preparation only: no historical backfill or rollout approval.
-- Existing sales, stock, amounts, PINs and permission grants are not rewritten.
-- Future writes gain private version/provenance metadata; exact owner review is
-- required before this file is applied to the named production project.
BEGIN;
SET LOCAL lock_timeout='3s';
SET LOCAL statement_timeout='60s';
DO $financial_preflight$
BEGIN
 IF EXISTS(SELECT 1 FROM pg_namespace WHERE nspname IN(
  'fin62_preparation','fin62_evidence_preparation','fin62_cloud_preparation',
  'fin62_version_preparation','fin62_origin_preparation','fin62_action_preparation',
  'fin62_history_preparation','fin62_web_preparation','fin62_live_preparation',
  'fin62_admin_preparation','fin62_rollout_preparation')) THEN
  RAISE EXCEPTION 'FIN62_EXISTING_METADATA_REQUIRES_REVIEW';
 END IF;
END $financial_preflight$;
`;
  const sql = canonical(header + sources.map(item => `\n-- Source: ${item.source}\n-- Canonical source SHA256: ${item.sha256}\n${item.body}`).join('') + `
DO $financial_postflight$
BEGIN
 IF NOT fin62_live_preparation.installation_ready()
  OR EXISTS(SELECT 1 FROM fin62_rollout_preparation.approvals)
  OR EXISTS(SELECT 1 FROM fin62_history_preparation.protected_shifts) THEN
  RAISE EXCEPTION 'FIN62_FINAL_INSTALLATION_NOT_READY';
 END IF;
END $financial_postflight$;
NOTIFY pgrst,'reload schema';
COMMIT;
`);
  return { sql, sources: sources.map(({source, sha256}) => ({source, sha256})) };
}
function outputs() {
  const cloud = renderCloudUpgrade();
  const local = ['025_shift_financial_bases.sql', '026_shift_financial_operations.sql'].map(name => ({
    source: 'scripts/preparation/' + name, file: 'database/sqlserver/prepared/' + name,
    text: read('scripts/preparation/' + name),
  }));
  const artifacts = [{ file: cloudPath, text: cloud.sql }, ...local.map(({file, text}) => ({file, text}))];
  const manifest = {
    status: 'candidate_not_approved_not_applied', encoding: 'UTF-8, LF, no BOM',
    cloudTarget: { organizationId: 'bjxgimekljzlnwejuawj', project: 'pos', projectId: 'qhrufhtbeguxydenzfey', url: 'https://qhrufhtbeguxydenzfey.supabase.co', database: 'postgres' },
    localTarget: 'Identify and approve each actual SQL Server/database separately. Never infer it from this manifest.',
    sources: cloud.sources,
    artifacts: artifacts.map(({file, text}) => ({file, sha256: sha256(text), bytes: Buffer.byteLength(text, 'utf8')})),
    boundaries: ['No live application approval', 'No rollout approval rows', 'No historical backfill or business-row rewrite', 'No PIN or permission-grant rewrite', 'Separate SHIFT63 cloud/local rule files must follow in the reviewed order', 'Local metadata files are individually transactional; no cross-database atomicity is claimed'],
  };
  return [...artifacts, { file: manifestPath, text: JSON.stringify(manifest, null, 2) + '\n' }];
}
if (require.main === module) {
  assert(['--check', '--write'].includes(process.argv[2]) && process.argv.length === 3, 'Use --check or --write; this script never applies SQL.');
  for (const {file, text} of outputs()) {
    const target = path.join(root, file);
    if (process.argv[2] === '--write') { fs.mkdirSync(path.dirname(target), {recursive:true}); fs.writeFileSync(target, text, 'utf8'); }
    else assert(fs.existsSync(target) && fs.readFileSync(target, 'utf8') === text, 'Regenerate release candidate: ' + file);
    console.log(file + ' ' + sha256(text));
  }
}
module.exports = { renderCloudUpgrade, outputs };
